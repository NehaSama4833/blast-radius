"""Replay real Python supply-chain incidents on the real PyPI dependency graph.

For each incident the culprit is a real release (package, version, upload time). We build the real ecosystem graph
(15,000 packages, their required dependencies, 1.2 million real releases) in FalkorDB, then simulate which packages'
CI starts failing: a random share of the culprit's direct dependents, a few of their own dependents (breakage
spreads), and some unrelated failures as noise. The question to the tools: which release, among every release
uploaded in the 48 hours before the first failure, caused this?

    python -m bench.pypi_incidents            # builds the graph (~30 s), runs all methods, writes the results

What is real: the packages, the dependency edges (as of the snapshot date), every release time, and the culprit
release of each incident. What is simulated: which dependents fail, and the noise. Seeds are fixed.
"""
