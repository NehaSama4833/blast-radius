SPLITS = {"dev": DEV, "test": TEST}
SEEDS = (1, 2, 3)
GRAPH = "pypi_bench"


def ts(iso):
    return int(datetime.fromisoformat(iso.replace("Z", "+00:00")).timestamp())


def make_scenarios(snap, incidents):
    """Deterministic failing sets. Uses only the snapshot, never FalkorDB, so scenarios are independent of the tools."""
    req = edges(snap, "sync")
    dependents = defaultdict(set)
    for a, b in req:
        dependents[b].add(a)
    names = sorted(snap["packages"])
    out = []
    for pkg, ver, iso, yanked, why in incidents:
        for seed in SEEDS:
            rng = random.Random(f"{pkg}-{ver}-{seed}")
            direct = sorted(dependents[pkg])
            k = max(3, min(40, int(len(direct) * rng.uniform(0.15, 0.5))))
            failing = set(rng.sample(direct, min(k, len(direct))))
            for f in sorted(failing):                                  # breakage spreads one more hop, sometimes
                nxt = sorted(dependents[f] - failing)
                if nxt and rng.random() < 0.3:
                    failing.add(rng.choice(nxt))
            near = _within(dependents, pkg, 3)
            noise = [n for n in rng.sample(names, 60) if n not in near and n != pkg][:rng.randint(2, 5)]
            failing |= set(noise)
            first = ts(iso) + rng.randint(1, 6) * 3600                 # CI notices 1 to 6 hours after the upload
            out.append(dict(id=f"{pkg}-{ver}-s{seed}", culprit=pkg, version=ver, released=ts(iso), yanked=yanked,
                            first_failure=first, failing=sorted(failing), noise=sorted(noise), why=why))
    return out


def _within(dependents, pkg, hops):
    seen, frontier = {pkg}, {pkg}
    for _ in range(hops):
        frontier = {d for f in frontier for d in dependents[f]} - seen
        seen |= frontier
    return seen


# ---------- methods ----------
def releases_in_window(g, t0, t1):
    return g.query("MATCH (d:Deploy)-[:TO]->(s:Service) WHERE d.ts >= $a AND d.ts <= $b "
                   "RETURN s.name, d.ts, s.downloads_30d", {"a": t0, "b": t1}).result_set


def rank_of(names, culprit):
    return names.index(culprit) + 1 if culprit in names else None


def run(scenarios, g, snap):
    req = edges(snap, "sync")
    deps_of = defaultdict(set)
    for a, b in req:
        deps_of[a].add(b)
    results = []
    for sc in scenarios:
        at = sc["first_failure"]
        t0 = at - 48 * 3600
        window = releases_in_window(g, t0, at)
        newest = [n for n, _, _ in sorted(window, key=lambda r: -r[1])]
        newest = list(dict.fromkeys(newest))
        popular = list(dict.fromkeys(n for n, _, _ in sorted(window, key=lambda r: (-(r[2] or 0), r[0]))))
        t = time.time()
        res = suspect_releases(g, sc["failing"], at, window_h=48, hops=2, top_k=len(window) or 5).data
        took = time.time() - t
        cov_rank = [s["package"] for s in res["suspects"]]
        f1_rank = [s["package"] for s in sorted(res["suspects"], key=lambda s: (-s["f1"], -s["coverage"], -s["released_at"], s["package"]))]
        # independent check of the graph walk: Python BFS over the same snapshot edges
        released = {n for n, _, _ in window}
        want = defaultdict(set)
        for f in sc["failing"]:
            for c in _down(deps_of, f, 2):
                if c in released:
                    want[c].add(f)
        got = {s["package"]: s["explains"] for s in res["suspects"]}
        bfs_agrees = got == {c: len(v) for c, v in want.items()}
        results.append(dict(id=sc["id"], culprit=sc["culprit"], n_failing=len(sc["failing"]), releases_in_window=len(window),
                            ranks=dict(f1=rank_of(f1_rank, sc["culprit"]), coverage=rank_of(cov_rank, sc["culprit"]),
                                       newest=rank_of(newest, sc["culprit"]), popular=rank_of(popular, sc["culprit"])),
                            top3=cov_rank[:3], seconds=round(took, 3), bfs_agrees=bfs_agrees))
    return results


def _down(deps_of, start, hops):
    seen, frontier = {start}, {start}
    for _ in range(hops):
        frontier = {d for f in frontier for d in deps_of[f]} - seen
        seen |= frontier
    return seen


def summarize(results):
    out = {}
    for m in ("f1", "coverage", "newest", "popular"):
        rs = [r["ranks"][m] for r in results]
        out[m] = dict(top1=sum(1 for x in rs if x == 1), top3=sum(1 for x in rs if x and x <= 3),
                      found=sum(1 for x in rs if x), n=len(rs),
                      median_rank=sorted(x or 10**6 for x in rs)[len(rs) // 2])
    out["bfs_agrees"] = sum(r["bfs_agrees"] for r in results)
    out["median_seconds"] = sorted(r["seconds"] for r in results)[len(results) // 2]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=list(SPLITS), default="dev")
    a = ap.parse_args()
    incidents = SPLITS[a.split]
    out_path = f"bench/results/pypi_{a.split}.json"
    snap = load_snapshot()
    scenarios = make_scenarios(snap, incidents)
    blob = json.dumps(scenarios, sort_keys=True).encode()
    with open(f"bench/scenarios/pypi_{a.split}.json", "w") as fh:
        json.dump(scenarios, fh, indent=1)
    g = get_graph(GRAPH)
    try:
        g.delete()
    except Exception:
        pass
    g = get_graph(GRAPH)
    t = time.time()
    stats = load_pypi(g, snap)
    for pkg, ver, iso, yanked, _ in incidents:                       # yanked culprits: add the real release back
        if yanked:
            g.query("MATCH (s:Service {name:$p}) CREATE (:Deploy {id:$id, ts:$t, kind:'release', version:$v, "
                    "summary:$p + ' ' + $v + ' (later yanked)', diff:'', author:''})-[:TO]->(s)",
                    {"p": pkg, "v": ver, "t": ts(iso), "id": f"{pkg}=={ver}"})
    stats["load_seconds"] = round(time.time() - t, 1)
    results = run(scenarios, g, snap)
    summary = summarize(results)
    report = dict(split=a.split, snapshot_fetched_at=snap["fetched_at"], top_list_updated=snap.get("top_list_updated"), graph=stats,
                  scenarios_sha256=hashlib.sha256(blob).hexdigest(), n_scenarios=len(scenarios), summary=summary,
                  results=results)
    with open(out_path, "w") as fh:
        json.dump(report, fh, indent=1)
    print(f"graph: {stats}")
    print(f"{len(results)} scenarios ({len(incidents)} real incidents x {len(SEEDS)} seeds), scenarios sha256 {report['scenarios_sha256'][:12]}")
    for m in ("coverage", "f1", "newest", "popular"):
        s = summary[m]
        print(f"  {m:9s} top-1 {s['top1']:2d}/{s['n']}  top-3 {s['top3']:2d}/{s['n']}  median rank {s['median_rank']}")
    print(f"  graph walk equals a Python BFS in {summary['bfs_agrees']}/{len(results)}; median query {summary['median_seconds']} s")


if __name__ == "__main__":
    main()
